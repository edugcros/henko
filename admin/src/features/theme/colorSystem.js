const hexToRgb = value => {
  let v = String(value || '').replace('#', '')
  if (v.length === 3) v = [...v].map(c => c + c).join('')
  if (!/^[0-9a-f]{6}$/i.test(v)) return null
  return [0, 2, 4].map(i => parseInt(v.slice(i, i + 2), 16) / 255)
}

const luminance = rgb =>
  rgb
    .map(c => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
    .reduce((sum, c, i) => sum + c * [0.2126, 0.7152, 0.0722][i], 0)

// Contraste WCAG entre dos colores hex (1 a 21). null si alguno no es válido.
export const contrastRatio = (a, b) => {
  const x = hexToRgb(a)
  const y = hexToRgb(b)
  if (!x || !y) return null
  const [hi, lo] = [luminance(x), luminance(y)].sort((p, q) => q - p)
  return (hi + 0.05) / (lo + 0.05)
}

// Los colores efectivos de una tienda. El pie de página se agregó después de
// los otros roles: si la tienda todavía no lo eligió, la tienda lo pinta con
// el texto y el fondo invertidos, y acá se muestra lo mismo.
export const resolveThemeColors = (colors = {}) => {
  const merged = { ...DEFAULT_THEME_COLORS, ...colors }
  return {
    ...merged,
    footerBackground: colors.footerBackground || merged.text,
    footerText: colors.footerText || merged.background,
  }
}

